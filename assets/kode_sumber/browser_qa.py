from playwright.sync_api import sync_playwright
from pathlib import Path
BASE=Path(__file__).resolve().parent.parent
HTML=(BASE/'cek-keringanan-sanksi.html').read_text()
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True,executable_path='/usr/bin/chromium',args=['--no-sandbox'])
 for width,label in [(1360,'desktop'),(390,'mobile')]:
  page=browser.new_page(viewport={'width':width,'height':900}, device_scale_factor=1)
  errors=[]; page.on('pageerror',lambda err: errors.append(str(err)))
  page.set_content(HTML)
  page.locator('[data-scenario="late"]').click()
  page.locator('#next').click()
  def get_fields(): return page.locator('[data-field]').evaluate_all('(xs)=>xs.map(x=>x.dataset.field)')
  assert get_fields()==['document'],get_fields()
  page.locator('#f_document').select_option('STP')
  assert 'sptType' in get_fields() and 'article' not in get_fields(),get_fields()
  page.locator('#f_sptType').select_option('annual')
  page.locator('#f_sptYear').fill('2025')
  page.locator('#f_sptStatus').select_option('kb')
  page.locator('#f_actionDate').fill('2026-10-25')
  page.locator('#f_issueDate').fill('2026-10-12')
  page.locator('#f_principalConfirmed').select_option('no_base')
  assert 'principalDate' not in get_fields(),get_fields()
  page.locator('#f_sanctionState').select_option('unpaid')
  assert 'sanctionPrior' not in get_fields() and 'partialDate' not in get_fields(),get_fields()
  page.locator('#f_estimateChoice').select_option('no')
  page.locator('#next').click()
  step3fields=get_fields()
  assert 'objection' not in step3fields,step3fields
  page.locator('#f_stpLinked').select_option('no')
  assert 'objection' not in get_fields(),get_fields()
  page.locator('#f_otherRemedy').select_option('none')
  page.locator('#f_lawsuit').select_option('none')
  page.locator('#f_auctionCondition').select_option('no')
  page.locator('#f_applicationDate').fill('2027-01-10')
  page.locator('#f_submissionCount').select_option('1')
  page.locator('#f_docReady').select_option('yes')
  assert 'docApplication' in get_fields() and 'docAffidavit' in get_fields() and 'docLegalStatement' in get_fields()
  for k in ['docApplication','docAffidavit','docLegalStatement']: page.locator(f'#f_{k}').select_option('yes')
  page.locator('#next').click()
  print(label,'result state:',page.locator('.res-head').inner_text()[:165])
  assert '100%' in page.locator('.res-head').inner_text()
  assert errors==[],errors
  page.screenshot(path=str(Path(__file__).resolve().parent/f'{label}_hasil.png'),full_page=True)
  # Reset and test partial scenario conditional
  page.locator('#next').click()
  page.locator('.more-cases summary').click();page.locator('[data-scenario="stp144"]').click();page.locator('#next').click()
  assert 'article' not in get_fields() and 'sanctionProgram' not in get_fields()
  page.locator('#f_sanctionState').select_option('partial')
  assert 'paymentPath' in get_fields() and 'sanctionProgram' not in get_fields()
  page.locator('#f_paymentPath').select_option('yes')
  assert 'sanctionProgram' in get_fields() and 'partialDate' in get_fields(),get_fields()
  page.locator('#f_sanctionState').select_option('unpaid')
  assert 'sanctionProgram' not in get_fields() and 'partialDate' not in get_fields(),get_fields()
  # Another branch: docReady no hides affidavit
  page.locator('#f_issueDate').fill('2026-10-12')
  page.locator('#f_principalConfirmed').select_option('no_base')
  page.locator('#f_estimateChoice').select_option('no')
  page.locator('#next').click()
  page.locator('#f_submissionCount').select_option('2')
  assert 'previousDecision' in get_fields() and 'previousCase' in get_fields(),get_fields()
  page.locator('#f_submissionCount').select_option('1')
  assert 'previousDecision' not in get_fields(),get_fields()
  page.locator('#f_docReady').select_option('no')
  assert 'docAffidavit' not in get_fields(),get_fields()
  print(label,'adaptive UI tests PASS, js errors',len(errors))
  page.close()
 browser.close()
